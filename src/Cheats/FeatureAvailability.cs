using System;

namespace MoTrainer.Cheats
{
    /// <summary>
    /// 「哪些功能目前被**刻意停用**、为什么」—— 全工程唯一的一份。
    ///
    /// 与"未校准"是两件事：
    ///   · 未校准 = 字段位置还不知道 → 到校准页点一次就有了；
    ///   · 刻意停用 = 已经知道**现在这条路走不通**（真机实测推翻过），
    ///     校准数据却看着是好的 —— 这时 `IsCalibrated` 拦不住，必须显式停用。
    ///
    /// 为什么不让 `MainForm` 自己写一句就算：那句"电力暂时不能用"是本项目的**技术结论**，
    /// 不是界面文案。放在这里，自检可以断言它确实存在（`CheckUnavailableFeature`），
    /// 而不是"某处有句话、没人验证过"。
    ///
    /// 解除停用 = 删掉下面这条 + 真机验证新做法确实有效，**两件事必须一起做**。
    /// 只删不验 = 又把一个"能点但没用"的开关放出去，正是 `CLAUDE.md` §4.2 要禁的那件事。
    /// </summary>
    public static class FeatureAvailability
    {
        /// <summary>
        /// 电力：原做法（锁 `House + 0x53A4`）已被真机推翻，目前正在换路线重做。
        ///
        /// 证据链（三轮，全部只读或已还原）：
        ///   ① 2026-09-22 真机：写进去界面显示 30000，游戏**仍判"电力不足"** ——
        ///      那个位置只是**界面显示值**，不是游戏真正据以计算的产出；
        ///   ② 2026-10-09 00:22 真机「电力试探」：候选 `+0xD0` 写入生效、也确实还原了
        ///      （`已还原=是`），而界面电力读数 **260 → 260 → 260 纹丝不动** → 排除；
        ///   ③ 2026-10-09 凌晨：`+0x0E4` 的"类型对象"假设被真机数据否定
        ///      （兵营的类型目标里装着它自己的对象地址 → 那是按对象、不是按类型）。
        ///   仍未定位到真正的产出来源，故保持停用。
        /// </summary>
        private const string PowerReason =
            "原做法已被真机实测推翻，正在换一条路重新定位";

        private const string PowerDetail =
            "【暂不可用】这个开关现在打不开，是**故意的** —— 不是程序坏了。\n"
            + "\n"
            + "原因：原来的做法是去改游戏界面上显示的那个电力数字。真机实测证明它只是「显示值」——\n"
            + "改成 30000 时界面确实显示 30000，但游戏照样判「电力不足」。改了没用。\n"
            + "后来试的两个候选位置也都被实测否掉了（写入确实生效、也还原了，电力读数却纹丝不动）。\n"
            + "\n"
            + "所以现在要换一条路：改发电厂自己的「产出」，让游戏自己算出更多的电。\n"
            + "在那条路**真机验证通过之前**，这里保持关闭 —— 宁可点不了，也不给你一个\n"
            + "「开了却没效果」的开关（那才是真的坑人）。\n"
            + "\n"
            + "进展记录见 开发日志/2026-10-09.md；本功能的当前状态见 docs/04 的 [S4-3]。";

        /// <summary>该功能被刻意停用的简短原因；空串 = 没有停用。</summary>
        public static string ReasonFor(CheatId id)
        {
            switch (id)
            {
                case CheatId.PowerOutput: return PowerReason;
                default: return "";
            }
        }

        /// <summary>该功能被刻意停用的完整说明（鼠标悬停时显示）；空串 = 没有停用。</summary>
        public static string DetailFor(CheatId id)
        {
            switch (id)
            {
                case CheatId.PowerOutput: return PowerDetail;
                default: return "";
            }
        }
    }
}

using System;

namespace MoTrainer.Cheats
{
    /// <summary>
    /// 「哪些功能目前被**刻意停用**、为什么」—— 全工程唯一的一份。
    ///
    /// 与"未校准"是两件事：
    ///   · 未校准 = 字段位置还不知道 → 到校准页点一次就有了；
    ///   · 刻意停用 = 已经知道**现在这条路走不通**（真机实测推翻过），
    ///     校准数据却看着是好的 —— 这时 `IsCalibrated` 拦不住，必须显式停用。
    ///
    /// 为什么不让 `MainForm` 自己写一句就算：那句"电力暂时不能用"是本项目的**技术结论**，
    /// 不是界面文案。放在这里，自检可以断言它确实存在（`CheckUnavailableFeature`），
    /// 而不是"某处有句话、没人验证过"。
    ///
    /// 解除停用 = 删掉下面这条 + 真机验证新做法确实有效，**两件事必须一起做**。
    /// 只删不验 = 又把一个"能点但没用"的开关放出去，正是 `CLAUDE.md` §4.2 要禁的那件事。
    /// </summary>
    public static class FeatureAvailability
    {
        /// <summary>
        /// 电力：**2026-10-09 已解除停用** —— 产出值定位成功并完成接线。
        ///
        /// 记录一下它为什么曾经被停用、又凭什么恢复（整条证据链）：
        ///   ① 2026-09-22 真机：写 `House + 0x53A4`（界面显示值）没用 —— 界面显示 30000，
        ///      游戏照样判「电力不足」。那个位置只是**界面显示值**；
        ///   ② 2026-10-09 真机「电力试探」：候选 `+0xD0` 写入生效、也确实还原了
        ///      （`已还原=是`），而读数纹丝不动 → 排除；`+0x0E4` 的"类型对象"假设
        ///      被真机数据否定（兵营的类型目标里装着它自己的对象地址 → 按对象、不是按类型）；
        ///   ③ **2026-10-09 定案（零写入证明）**：产出值记在**建筑类型对象（同型号共用一份的"说明书"）**
        ///      的 `+0xEE0`。把用户名下全部建筑按型号求和 —— 磁暴反应堆×3×150 + 核反应堆×2×2000 +
        ///      建造厂×1×60 = **4510**，与游戏自己显示的电力产出一分不差；且全场只有这一个偏移
        ///      同时满足"磁暴反应堆 150、核反应堆 2000"。证据见 `开发日志/2026-10-09.md` 第十节。
        ///
        /// **恢复可用 ≠ 已验证**：功能的第一次真机运行才是最终验收。
        /// 实现见 `PowerBoost`；卡片上必须如实写明"同型号共用说明书 → 敌方同型号建筑也会受益"。
        /// </summary>
        private const string PowerReasonWhenDisabled = "";

        /// <summary>该功能被刻意停用的简短原因；空串 = 没有停用。</summary>
        public static string ReasonFor(CheatId id)
        {
            switch (id)
            {
                case CheatId.PowerOutput: return PowerReasonWhenDisabled;
                default: return "";
            }
        }

        /// <summary>该功能被刻意停用的完整说明（鼠标悬停时显示）；空串 = 没有停用。</summary>
        public static string DetailFor(CheatId id)
        {
            return "";
        }
    }
}
